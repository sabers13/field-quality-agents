"""Assembling the offline export and its bundled JSON."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from field_quality_agents.export.site import assemble_site, build_static_export, write_bundle


def _data(root: Path) -> Path:
    data = root / "data"
    case = {"id": "2052717", "received_at": "2025-03-01", "make": "ACME"}
    for name, payload in {
        "manifest.json": {"run_id": "replay", "counts": {"cases": 1}},
        "command_centre.json": {"window": "365d"},
        "cases.json": [case],
        "cases/2052717.json": {"case": case},
        "issues.json": [],
        "comparison.json": None,
        "weekly_report.json": None,
        "replay.json": {"runs": [], "events": {}},
    }.items():
        path = data / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload), encoding="utf-8")
    return data


def test_bundle_holds_every_page_in_one_script(tmp_path: Path) -> None:
    data = _data(tmp_path)
    target = write_bundle(data)

    text = target.read_text(encoding="utf-8")
    assert text.startswith("/* Generated by `fqa export`")
    payload = json.loads(text.split("=", 1)[1].strip().removesuffix(";"))
    assert payload["manifest"]["run_id"] == "replay"
    assert payload["caseDetails"]["2052717"]["case"]["make"] == "ACME"
    assert payload["replay"] == {"runs": [], "events": {}}


def test_site_copies_the_build_and_loads_the_bundle(tmp_path: Path) -> None:
    web = tmp_path / "web"
    (web / "assets").mkdir(parents=True)
    (web / "index.html").write_text(
        '<html><head><script type="module" crossorigin src="./assets/app.js"></script>'
        '<link rel="stylesheet" crossorigin href="./assets/app.css"></head><body></body></html>',
        encoding="utf-8",
    )
    (web / "assets" / "app.js").write_text("console.log(1)", encoding="utf-8")
    (web / "assets" / "app.css").write_text("body{}", encoding="utf-8")
    out = tmp_path / "dist"
    out.mkdir()

    root = assemble_site(web, out)

    html = (root / "index.html").read_text(encoding="utf-8")
    assert html.count('src="./data/bundle.js"') == 1
    # The export must load from file://: no module scripts, no CORS attributes.
    assert 'type="module"' not in html
    assert "crossorigin" not in html
    assert '<script defer src="./assets/app.js">' in html
    assert (root / "assets" / "app.js").is_file()


def test_export_refuses_without_a_dashboard_build(tmp_path: Path) -> None:
    with pytest.raises(FileNotFoundError, match="make web-build"):
        build_static_export(
            results_dir=tmp_path / "runs",
            out_dir=tmp_path / "dist",
            web_dir=tmp_path / "missing-web",
            baseline_dir=tmp_path / "baseline",
        )
