"""Assemble the offline portfolio export under ``dist/field-quality-agents/``.

The export is one self-contained directory: the built dashboard, the JSON data
files documented in ``docs/INTERFACES.md``, and ``data/bundle.js`` which
assigns the same data to ``window.__FQA_BUNDLE__``. The bundle lets the page
open straight from the filesystem (``file://``) with no server and no network;
the individual JSON files stay for inspection and for the reproducibility
manifest.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from field_quality_agents.export.showcase import choose_examples
from field_quality_agents.run.dashboard import export_dashboard

__all__ = ["assemble_site", "build_static_export", "write_bundle"]

_SCRIPT_MARKER = "</head>"


def _read(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _ordered_cases(data: Path) -> list[dict[str, Any]]:
    cases = _read(data / "cases.json")
    return cases if isinstance(cases, list) else []


def _clean(root: Path) -> None:
    """Remove a previous export so hashed assets never accumulate."""

    resolved = root.resolve()
    if resolved == Path("/") or resolved == Path.cwd().resolve() or resolved.name == "":
        raise ValueError(f"refusing to clear {resolved} as an export directory")
    if not resolved.exists():
        return
    if not resolved.is_dir():
        raise ValueError(f"export path {resolved} is not a directory")
    for child in resolved.iterdir():
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child)
        else:
            child.unlink()


def write_bundle(data_dir: str | Path) -> Path:
    """Write ``data/bundle.js`` from the JSON files already in ``data_dir``."""

    data = Path(data_dir)
    cases = _ordered_cases(data)
    bundle = {
        "manifest": _read(data / "manifest.json"),
        "commandCentre": _read(data / "command_centre.json"),
        "cases": cases,
        "caseDetails": {
            str(case["id"]): _read(data / "cases" / f"{case['id']}.json") for case in cases
        },
        "issues": _read(data / "issues.json"),
        "comparison": _read(data / "comparison.json"),
        "weeklyReport": _read(data / "weekly_report.json"),
        "replay": _read(data / "replay.json"),
    }
    payload = json.dumps(bundle, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    target = data / "bundle.js"
    target.write_text(
        "/* Generated by `fqa export`; regenerate with `make all`. */\n"
        f"window.__FQA_BUNDLE__ = {payload};\n",
        encoding="utf-8",
    )
    return target


def assemble_site(web_dir: str | Path, out_dir: str | Path) -> Path:
    """Copy the built dashboard into the export and load the bundled data."""

    web = Path(web_dir)
    index = web / "index.html"
    if not index.is_file():
        raise FileNotFoundError(
            f"{index} is missing; run `make web-build` before `fqa export`"
        )
    root = Path(out_dir)
    for child in web.iterdir():
        target = root / child.name
        if child.is_dir():
            shutil.copytree(child, target, dirs_exist_ok=True)
        else:
            shutil.copy2(child, target)

    html = (root / "index.html").read_text(encoding="utf-8")
    # The app is built as one IIFE; file:// blocks ES modules and CORS-enabled
    # scripts, so the export loads it as a plain deferred script after the
    # bundle data has run.
    html = html.replace(' type="module"', "").replace(" crossorigin", "")
    html = html.replace('<script src="./assets/', '<script defer src="./assets/', 1)
    tag = '    <script src="./data/bundle.js"></script>\n'
    if tag.strip() not in html:
        if _SCRIPT_MARKER not in html:
            raise ValueError(f"{root / 'index.html'} has no </head> to load the bundle from")
        html = html.replace(_SCRIPT_MARKER, f"{tag}  {_SCRIPT_MARKER}", 1)
    (root / "index.html").write_text(html, encoding="utf-8")
    return root


def build_static_export(
    *,
    results_dir: str | Path = "results/runs",
    run_id: str | None = None,
    out_dir: str | Path = "dist/field-quality-agents",
    web_dir: str | Path = "web/dist",
    baseline_dir: str | Path = "results/baseline",
) -> Path:
    """Write the full offline export and return its root."""

    web = Path(web_dir)
    if not (web / "index.html").is_file():
        raise FileNotFoundError(
            f"{web / 'index.html'} is missing; run `make web-build` before `fqa export`"
        )
    root = Path(out_dir)
    _clean(root)
    root.mkdir(parents=True, exist_ok=True)

    from field_quality_agents.api.store import FileResultStore

    store = FileResultStore(results_dir, run_id=run_id)
    active = store.active_run_id()
    examples = choose_examples(Path(results_dir) / active, baseline_dir) if active else []
    export_dashboard(
        results_dir=results_dir,
        run_id=run_id,
        out_dir=root,
        examples=examples,
    )
    write_bundle(root / "data")
    return assemble_site(web_dir, root)
